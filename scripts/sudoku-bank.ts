// Builds the offline Classic Sudoku bank (shared/sudoku/bank.json) — own generator, no third-party puzzles.
// Each seed → random full grid → symmetric hole digging while the solution stays unique → graded by the
// lowest logic tier that solves it. Puzzles beyond the hard tier are discarded. Fully reproducible from seeds.
// Usage: npx tsx scripts/sudoku-bank.ts [perLevel=40]
import { writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { DIFFICULTIES, DIFFICULTY_VERSION, RULES_VERSION, countSolutions, grade, gridToString, logicSolve, rng, techniqueCounts, type Difficulty, type Grid } from '../shared/sudoku/engine';

const PER = Number(process.argv[2] ?? 40);
const GENERATOR = 'jy-sudoku-gen-1';

function fullGrid(rand: () => number): Grid {
  const g = new Array(81).fill(0);
  const ok = (i: number, d: number) => {
    const r = Math.floor(i / 9),
      c = i % 9;
    for (let k = 0; k < 9; k++) if (g[r * 9 + k] === d || g[k * 9 + c] === d) return false;
    const r0 = r - (r % 3),
      c0 = c - (c % 3);
    for (let a = 0; a < 3; a++) for (let b = 0; b < 3; b++) if (g[(r0 + a) * 9 + c0 + b] === d) return false;
    return true;
  };
  const rec = (i: number): boolean => {
    if (i === 81) return true;
    const ds = [1, 2, 3, 4, 5, 6, 7, 8, 9].sort(() => rand() - 0.5);
    for (const d of ds)
      if (ok(i, d)) {
        g[i] = d;
        if (rec(i + 1)) return true;
      }
    g[i] = 0;
    return false;
  };
  rec(0);
  return g;
}

function dig(solution: Grid, rand: () => number, minGivens: number): Grid {
  const g = solution.slice();
  const order = Array.from({ length: 41 }, (_, i) => i).sort(() => rand() - 0.5); // 180° pairs (40 is the centre)
  let givens = 81;
  for (const i of order) {
    const j = 80 - i;
    const n = i === j ? 1 : 2;
    if (givens - n < minGivens) continue;
    const a = g[i],
      b = g[j];
    g[i] = 0;
    g[j] = 0;
    if (countSolutions(g, 2).count === 1) givens -= n;
    else {
      g[i] = a;
      g[j] = b;
    }
  }
  return g;
}

const bank: Record<Difficulty, unknown[]> = { easy: [], medium: [], hard: [] };
const seen = new Set<string>();
let seed = 20261015;
let tried = 0;
const t0 = Date.now();
while (DIFFICULTIES.some((d) => bank[d].length < PER) && tried < 200000) {
  tried++;
  const s = seed++;
  const rand = rng(s);
  const solution = fullGrid(rand);
  // easy puzzles keep a few more givens; the others dig to (near-)minimal
  const want = DIFFICULTIES.find((d) => bank[d].length < PER)!;
  const minGivens = bank.easy.length < PER && tried % 3 === 0 ? 30 : 17;
  const givens = dig(solution, rand, minGivens);
  const key = gridToString(givens);
  if (seen.has(key)) continue;
  const level = grade(givens);
  if (!level || bank[level].length >= PER) continue;
  seen.add(key);
  const trace = logicSolve(givens, level);
  if (!trace.solved || gridToString(trace.grid) !== gridToString(solution)) throw new Error(`trace mismatch for seed ${s}`);
  const n = bank[level].length + 1;
  bank[level].push({
    puzzleId: `jy-su-${level[0]}-${String(n).padStart(3, '0')}-${createHash('sha256').update(key).digest('hex').slice(0, 8)}`,
    rulesVersion: RULES_VERSION,
    difficultyVersion: DIFFICULTY_VERSION,
    difficulty: level,
    givens: key,
    solution: gridToString(solution),
    source: { generator: GENERATOR, seed: s, minGivens },
    verification: { solutions: 1, givensCount: givens.filter(Boolean).length, logicSteps: trace.steps.length, techniques: techniqueCounts(trace.steps) },
  });
  void want;
}
const out = {
  rulesVersion: RULES_VERSION,
  difficultyVersion: DIFFICULTY_VERSION,
  generator: GENERATOR,
  generatedAt: new Date().toISOString().slice(0, 10),
  license: 'Generated by JY Games (GPL-3.0-or-later); no third-party puzzles',
  puzzles: [...bank.easy, ...bank.medium, ...bank.hard],
};
writeFileSync('shared/sudoku/bank.json', JSON.stringify(out, null, 1) + '\n');
console.log(`bank: easy ${bank.easy.length}, medium ${bank.medium.length}, hard ${bank.hard.length} from ${tried} grids in ${((Date.now() - t0) / 1000).toFixed(1)} s`);
